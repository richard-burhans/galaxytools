#!/usr/bin/env python3
"""Generate WF-I, the cs10 multiple alignment, as three workflows: split, roast, track.

    python3 assemble_wfi.py            # write wfi_{split,roast,track}.gxwf.yml
    python3 assemble_wfi.py --check    # fail if a committed document is stale
    python3 assemble_wfi.py --self-test

The plan is cannabis-genome reports/wfi_multiz_plan.md. UCSC's recipe it follows is autoMultiz.csh
per piece (kent src/hg/makeDb/doc/hg38/multiz100way.txt), with the bigMaf of vgp577way.txt.

  SPLIT  per species: maf_name_rows forward (rows cs10.<seq>, <species>.<hub seq>, by row position)
           -> ucsc_mafsplit_bed at cs10's cut list -> species:piece
         -> Apply rules: piece:species
  ROAST  per piece: multiz_roast over that piece's species (the inner list feeds the multiple input)
  TRACK  Apply rules: piece -> sequence:piece (the identifier <seq>.NN split at its last dot)
           -> maf_concat per sequence -> maf_name_rows species (g79X -> 79X)
           -> ucsc_maftobigmaf per sequence -> cat_multiple -> bedToBigBed bed3+1 with bigMaf.as

▶ THREE DOCUMENTS, NOT ONE (plan §4.7). A failed piece is re-run alone against SPLIT's durable
piece:species collection, and TRACK starts only when every piece is ok. A single workflow would tie the
whole run to the slowest and least lucky job.

▶ THE SPECIES COMES FROM CONTENT. The panel's MAFs carry no species prefixes and 35 genomes use bare
accessions as sequence names, so each MAF travels with a one-line `label<TAB>species` dataset in a
parallel list with the same identifiers (`names`), and maf_name_rows tells the rows apart by position.
The tools take element identifiers from nowhere, so they run the same as UDTs and as shed tools.

▶ ONE SWITCH FROM UDT TO SHED. `SOURCE = "shed"` pins each WF-I step to its Tool Shed guid at the
version its XML declares; `"udt"` pins the UDT id instead, for a server without the shed tools. The
documents are written for the shed; `--source udt` writes the UDT variants beside them.

⚠ NOT YET IN TRACK: the mafSummary track (hgLoadMafSummary is not on bioconda, plan D2), and
`-itemsPerSlot=4`, which UCSC passes to bedToBigBed for a bigMaf and the shed wrapper does not expose
(the file is valid without it, and slower to query).
"""
from __future__ import annotations

import argparse
import copy
import pathlib
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from assemble import tool_version  # noqa: E402,I202 -- one implementation of the XML version rule

ROOT = HERE.parent.parent
BANNER = "# GENERATED by assemble_wfi.py -- DO NOT EDIT BY HAND. Edit assemble_wfi.py and rerun.\n"
SHED = "toolshed.g2.bx.psu.edu/repos/richard-burhans"
#: key -> (shed repository, tool id, UDT id, XML). The version is the XML's, for the shed tool and the UDT alike.
WFI = {
    "name_rows": ("maf_name_rows", "maf_name_rows", "gt-maf-name-rows", "tools/maf_name_rows/maf_name_rows.xml"),
    "split": ("ucsc_mafsplit_bed", "ucsc_mafsplit_bed", "gt-ucsc-mafsplit-bed",
              "tools/ucsc_mafsplit_bed/mafsplit_bed.xml"),
    "roast": ("multiz_roast", "multiz_roast", "gt-multiz-roast", "tools/multiz_roast/multiz_roast.xml"),
    "concat": ("maf_concat", "maf_concat", "gt-maf-concat", "tools/maf_concat/maf_concat.xml"),
    "tobigmaf": ("ucsc_maftobigmaf", "ucsc_maftobigmaf", "gt-ucsc-maftobigmaf",
                 "tools/ucsc_maftobigmaf/maftobigmaf.xml"),
}
OTHER = {
    "bedtobigbed": (f"{SHED}/ucsc_bedtobigbed/ucsc_bedtobigbed", "tools/ucsc_kent/bedToBigBed.xml"),
    "cat_multiple": "toolshed.g2.bx.psu.edu/repos/mvdbeek/concatenate_multiple_datasets/cat_multiple/0.2",
}
APPLY_RULES = ("__APPLY_RULES__", "1.1.0")
#: A piece is <sequence>.NN, the sequence itself holding dots (NC_044370.1.03, small.00).
PIECE_RE = r"^(.*)\.([0-9]+)$"


def _tool(key: str, source: str) -> dict:
    repo, tid, udt, xml = WFI[key]
    version = tool_version(ROOT / xml)
    if source == "udt":
        return {"tool_id": udt, "tool_version": version}
    return {"tool_id": f"{SHED}/{repo}/{tid}/{version}", "tool_version": version}


def _bedtobigbed() -> dict:
    base, xml = OTHER["bedtobigbed"]
    version = tool_version(ROOT / xml)
    return {"tool_id": f"{base}/{version}", "tool_version": version}


def _swap() -> dict:
    """species:piece -> piece:species."""
    return {"rules": {"rules": [{"type": "add_column_metadata", "value": "identifier0"},
                                {"type": "add_column_metadata", "value": "identifier1"}],
                      "mapping": [{"type": "list_identifiers", "columns": [1, 0]}]}}


def _by_sequence() -> dict:
    """piece (<seq>.NN) -> sequence:piece, the identifier split at its last dot."""
    return {"rules": {"rules": [{"type": "add_column_metadata", "value": "identifier0"},
                                {"type": "add_column_regex", "target_column": 0, "expression": PIECE_RE,
                                 "group_count": 2}],
                      "mapping": [{"type": "list_identifiers", "columns": [1, 2]}]}}


def _rules(state: dict, doc: str, src: str) -> dict:
    return {"tool_id": APPLY_RULES[0], "tool_version": APPLY_RULES[1], "doc": doc, "in": {"input": src},
            "state": state}


