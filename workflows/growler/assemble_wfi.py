DOCS = {"wfi_split": split_doc, "wfi_roast": roast_doc, "wfi_track": track_doc}


def out_path(name: str, source: str) -> pathlib.Path:
    return HERE / (f"{name}.gxwf.yml" if source == "shed" else f"{name}.udt.gxwf.yml")


def dangling(doc: dict) -> list[str]:
    known = set(doc["inputs"]) | set(doc["steps"])
    out = [f"{n}.{k} <- {v}" for n, s in doc["steps"].items() for k, v in s["in"].items()
           if v.split("/")[0] not in known]
    out += [f"output {k}" for k, v in doc["outputs"].items() if v["outputSource"].split("/")[0] not in known]
    return out


def recipe_problems(docs: dict) -> list[str]:
    """What would make this a different recipe than the plan's, each named."""
    out = []
    if docs["wfi_split"]["steps"]["by_piece"]["state"] != _swap():
        out.append("split: by_piece does not swap species:piece into piece:species")
    if docs["wfi_track"]["steps"]["by_sequence"]["state"] != _by_sequence():
        out.append("track: by_sequence does not split the piece identifier at its last dot")
    if docs["wfi_split"]["steps"]["name_rows"]["state"].get("mode") != "forward":
        out.append("split: name_rows is not in forward mode")
    if docs["wfi_track"]["steps"]["rename_back"]["state"].get("mode") != "species":
        out.append("track: rename_back is not in species mode")
    want = {("wfi_split", "split", "input"): "name_rows/output", ("wfi_split", "by_piece", "input"): "split/pieces",
            ("wfi_roast", "roast", "pairwise"): "pieces", ("wfi_track", "concat", "pieces"): "by_sequence/output",
            ("wfi_track", "rename_back", "input"): "concat/output", ("wfi_track", "tobigmaf", "input"): "rename_back/output",
            ("wfi_track", "bigmaf", "bed"): "bigmaf_text/out_file1"}
    for (d, s, k), v in want.items():
        got = docs[d]["steps"][s]["in"].get(k)
        if got != v:
            out.append(f"{d}: {s}.{k} reads {got!r}, the recipe needs {v!r}")
    if docs["wfi_track"]["steps"]["bigmaf"]["state"].get("type") != "bed3+1":
        out.append("track: bedToBigBed is not -type=bed3+1")
    return out


def piece_split(identifier: str) -> tuple[str, str] | None:
    """What by_sequence's regex makes of a piece identifier, for the self-test."""
    import re
    m = re.match(PIECE_RE, identifier)
    return (m.group(1), m.group(2)) if m else None


def build(source: str) -> dict:
    return {name: f(source) for name, f in DOCS.items()}


def self_test() -> int:
    fails = 0

    def check(name: str, cond: bool) -> None:
        nonlocal fails
        fails += not cond
        print(f"  {'ok ' if cond else 'FAIL'} {name}")

    for source in ("shed", "udt"):
        docs = build(source)
        check(f"[{source}] no dangling connection", all(dangling(d) == [] for d in docs.values()))
        check(f"[{source}] the plan's recipe", recipe_problems(docs) == [])
        for key, (repo, tid, udt, xml) in WFI.items():
            version = tool_version(ROOT / xml)
            ids = {s["tool_id"] for d in docs.values() for s in d["steps"].values()}
            want = udt if source == "udt" else f"{SHED}/{repo}/{tid}/{version}"
            check(f"[{source}] {key} pins {want}", want in ids)
    check("NC_044370.1.03 -> (NC_044370.1, 03)", piece_split("NC_044370.1.03") == ("NC_044370.1", "03"))
    check("small.00 -> (small, 00)", piece_split("small.00") == ("small", "00"))
    check("NW_022060417.1.00 -> (NW_022060417.1, 00)", piece_split("NW_022060417.1.00") == ("NW_022060417.1", "00"))
    docs = build("shed")
    broken = copy.deepcopy(docs)
    broken["wfi_split"]["steps"]["by_piece"]["state"]["rules"]["mapping"][0]["columns"] = [0, 1]
    check("  and a regroup that does not swap is caught", recipe_problems(broken) != [])
    broken = copy.deepcopy(docs)
    broken["wfi_track"]["steps"]["tobigmaf"]["in"]["input"] = "concat/output"
    check("  and a bigMaf built before the names are restored is caught", recipe_problems(broken) != [])
    for source in ("shed", "udt"):
        for name, d in build(source).items():
            p = out_path(name, source)
            if p.exists():
                check(f"{p.name} matches a fresh build", yaml.safe_load(p.read_text(encoding="utf-8")) == d)
    print("\nall tests passed" if not fails else f"\n{fails} FAILED")
    return 1 if fails else 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args()
    if a.self_test:
        return self_test()
    stale = []
    for source in ("shed", "udt"):
        docs = build(source)
        problems = [p for d in docs.values() for p in dangling(d)] + recipe_problems(docs)
        if problems:
            sys.exit("REFUSING:\n  " + "\n  ".join(problems))
        for name, d in docs.items():
            p = out_path(name, source)
            if a.check:
                if not p.exists() or yaml.safe_load(p.read_text(encoding="utf-8")) != d:
                    stale.append(p.name)
                continue
            p.write_text(BANNER + yaml.safe_dump(d, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8")
            print(f"wrote {p.name} ({len(d['steps'])} steps)")
    if a.check:
        if stale:
            sys.exit(f"stale: {', '.join(stale)} -- run assemble_wfi.py and commit")
        print("WF-I documents are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
