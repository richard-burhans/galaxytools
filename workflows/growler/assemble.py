#!/usr/bin/env python3
"""Assemble the workflows that inline Growler as a subworkflow.

    ./assemble.py                 # writes growler_pair.gxwf.yml and growler_panel.gxwf.yml
    ./assemble.py --check         # non-zero if either committed file is stale
    ./assemble.py --self-test

TWO DOCUMENTS ARE GENERATED FROM ONE, and they are different shapes on purpose:

  growler_pair.gxwf.yml   ONE genome pair in, `cleaned_chains` / `rbest_chains` / `pairwise_axt`
                          out. The per-pair WRAPPER: it creates the chromosome-pair axis inside
                          itself and collapses it again before returning, so its caller never
                          sees a list:list. This is what WF-C maps over.
  growler_panel.gxwf.yml  every ordered genome pair, Growler alone, alignments out. The
                          standalone demonstration; it has no chain steps.

⛔ THERE IS ONE SOURCE OF TRUTH AND IT IS `growler.gxwf.yml`. gxformat2 has no include: a
subworkflow step carries the whole child document inline under `run:`. Writing the panel workflow
by hand would mean a second copy of Growler that drifts from the first, which is the defect this
project already has four instances of (two scripts, four copies, in two repositories). So the
panel file is GENERATED, and `--check` fails the build if it stops matching.

▶ WHY THE PANEL CASE IS A SUBWORKFLOW AT ALL, rather than the same steps flattened:

Galaxy does not broadcast a dataset across nesting levels. Flattened, `growler_lastz` would have to
be mapped over the INNER (chromosome-pair) level while its 2bits sit at the OUTER (genome-pair)
level, and there is no native operation that expands one dataset across N identifiers -- brc-tools
works around this by materialising parallel `list:list` collections with matching identifiers.

Inside a Growler invocation there is only one level: one genome pair, two 2bits as plain `data`
inputs, a flat collection of pair files. The nesting problem does not get solved here, it stops existing.
And the outer `list:list` is produced for free: a subworkflow mapped over a list, emitting a
collection, yields `list:list` with outer identifiers preserved -- measured on usegalaxy.org 26.1
on 2026-09-17, in exactly this shape.
"""
