# ------------------------------------------------------------------------ the import size guard

#: zlib bytes at which a single annotation is worth a note, and at which it is a problem.
#:
#: ⛔ usegalaxy.org answers `POST /api/workflows` with `500 {"err_msg": "Uncaught exception in
#: exposed API method:"}` AND NO TRACEBACK once an annotation gets too big. gxformat2 converts the
#: same file locally without complaint and `planemo workflow_lint` passes, so nothing in this
#: repository's checks would notice -- an un-importable workflow reaches main unseen, which has
#: already happened once in a sibling repository.
#:
#: ⚠ THE LIMIT TRACKS COMPRESSED SIZE, SO LENGTH IS THE WRONG THING TO MEASURE. Measured on
#: usegalaxy.org 26.1 varying only the top-level doc: 4,200 characters of `'a'` compress to 28
#: bytes and import fine; 3,000 characters of base64 compress to 2,290 and 500. A bisect over it
#: looks incoherent -- one added space flips 200 to 500 -- because the trigger is a threshold on a
#: derived size, not an offending substring.
ANNOTATION_NOTE_BYTES = 1_600
ANNOTATION_PROBLEM_BYTES = 1_900


def annotation_sizes(document: dict) -> list[tuple[int, str, int]]:
    """`(zlib bytes, where, characters)` for every annotation in a workflow, largest first.

    Every `doc` is its own annotation and each is capped separately, so the SUM is not the thing to
    measure either -- a document of many small docs is fine and one long step doc is not.
    """
    items = [("<workflow doc>", document.get("doc", ""))]
    for section in ("inputs", "steps", "outputs"):
        for name, value in (document.get(section) or {}).items():
            if isinstance(value, dict):
                items.append((f"{section[:-1]} {name}", value.get("doc", "")))
    sized = [(len(zlib.compress((text or "").encode())), where, len(text or "")) for where, text in items]
    return sorted(sized, reverse=True)


def annotation_complaints(document: dict, label: str) -> list[str]:
    """Anything at or over the problem threshold, as complaints. Empty means it should import."""
    return [
        f"{label}: {where} is {size:,} zlib bytes ({chars:,} chars) -- at or over the "
        f"{ANNOTATION_PROBLEM_BYTES:,}-byte import limit; usegalaxy.org will 500 with no traceback"
        for size, where, chars in annotation_sizes(document)
        if size >= ANNOTATION_PROBLEM_BYTES
    ]


def render(growler: dict) -> str:
    return BANNER + yaml.safe_dump(build(growler), sort_keys=False, width=100, allow_unicode=True)


def render_pair(growler: dict) -> str:
    return BANNER + yaml.safe_dump(build_pair(growler), sort_keys=False, width=100, allow_unicode=True)


def self_test() -> int:
    failures = []

    def check(label, got, want):
        if got != want:
            print(f"not ok - {label}\n     got: {got}\nexpected: {want}")
            failures.append(label)
        else:
            print(f"ok - {label}")

    child = {"class": "GalaxyWorkflow", "label": "kid",
             "inputs": {"target_fasta": {"type": "data"}, "query_fasta": {"type": "data"},
                        "scores": {"type": "data", "optional": True},
                        "output_format": {"type": "text", "default": "axt"}},
             "outputs": {"alignments": {"outputSource": "x/out"}}, "steps": {}}
    panel = build(child)

    check("the child is inlined, not referenced", panel["steps"]["growler"]["run"], child)
    check("self-pairs are filtered out of both arms",
          sorted(k for k, v in panel["steps"].items() if v.get("tool_id") == "__FILTER_FROM_FILE__"),
          ["queries", "targets"])
    # ▶ output_a must reach the TARGET and output_b the QUERY. Crossing them silently aligns every
    # pair backwards: the run succeeds, the chains are all reversed, and nothing raises.
    check("output_a drives target", panel["steps"]["targets"]["in"]["input"], "pairs/output_a")
    check("output_b drives query", panel["steps"]["queries"]["in"]["input"], "pairs/output_b")
    # ⛔ THE FILTER DIRECTION. `self_pairs` lists the diagonal, so the diagonal must be REMOVED.
    # `remove_if_absent` keeps only what the file names -- i.e. only the self-pairs -- which is the
    # exact inverse, runs perfectly happily, and aligns every genome against itself. This assertion
    # exists because the first version of this file had it backwards.
    for arm in ("targets", "queries"):
        check(f"{arm}: the diagonal is removed, not retained",
              panel["steps"][arm]["state"]["how"]["how_filter"], "remove_if_present")

    check("growler takes the filtered lists, not the raw cross product",
          [panel["steps"]["growler"]["in"]["target_fasta"], panel["steps"]["growler"]["in"]["query_fasta"]],
          ["targets/output_filtered", "queries/output_filtered"])
    # ⛔ THE FORMAT MUST REACH THE CHILD FROM THE PANEL, NOT FROM THE CHILD'S OWN DEFAULT. Drop
    # this connection and every pair silently falls back to whatever growler.gxwf.yml defaults to
    # -- which is a perfectly valid run, in the wrong format, discovered at the chain step.
    check("the panel drives the child's output format",
          panel["steps"]["growler"]["in"].get("output_format"), "output_format")
    check("  and the panel's own default is the chain path's format",
          panel["inputs"]["output_format"]["default"], "axt")

    # every name the panel connects to must exist in the child, or the import binds nothing
    for slot in ("target_fasta", "query_fasta", "scores", "output_format"):
        check(f"child declares input {slot}", slot in child["inputs"], True)
    check("child declares the output the panel exports",
          panel["outputs"]["alignments"]["outputSource"].split("/")[1] in child["outputs"], True)
    check("render round-trips through yaml",
          yaml.safe_load(render(child))["steps"]["growler"]["run"]["label"], "kid")

    # ------------------------------------------------------------------------------ the wrapper
    pair = build_pair(child)
    check("the wrapper inlines the child too", pair["steps"]["growler"]["run"], child)
    check("the wrapper exports exactly what WF-C declares",
          sorted(pair["outputs"]), ["cleaned_chains", "pairwise_axt", "rbest_chains"])

    # ⛔ THE COLLAPSE MUST EXIST ON BOTH BRANCHES. Either one left mapped hands the caller a
    # collection where WF-C declares a dataset, and the caller -- WF-C -- then sees list:list,
    # which is the single property this document exists to prevent. The plan's own §4 diagram
    # omitted the AXT one, so this is asserted rather than trusted.
    check("the chain branch collapses at chainMergeSort",
          pair["steps"]["chainmergesort"]["in"]["in_chains"], "axtchain/out")
    check("the axt branch collapses too, by concatenation",
          pair["steps"]["axt_concat"]["in"]["input"], "growler/alignments")
    for name, source in pair["outputs"].items():
        collapsed = source["outputSource"].split("/")[0] not in ("growler", "axtchain")
        check(f"  {name} comes from a collapsed step", collapsed, True)

    # ⛔ chainMergeSort REPLACES the chainSort WF-C runs here; it must not be reinstated between
    # them, because its output is already score-ordered and that is chainPreNet's precondition.
    check("no chainSort sits between the merge and chainPreNet",
          pair["steps"]["chainprenet"]["in"]["in_chain"], "chainmergesort/out")

    # ⛔ THE RECIPROCAL-BEST ARM SWAPS BACK. Without rb_swap2/rb_sort2 the rbest chains are
    # QUERY-referenced and every consumer reads them as target-referenced with nothing raising.
    # §4's diagram omitted both steps, and the acceptance test as written could not have caught it.
    check("rbest is swapped back before it is exported",
          [pair["steps"]["rb_swap2"]["in"]["in_chain"], pair["outputs"]["rbest_chains"]["outputSource"]],
          ["rb_stitch/output", "rb_sort2/out"])
    # ⚠ and the rbest net runs in the SWAPPED frame, so its sizes files are the other way round
    check("the rbest net takes the sizes swapped",
          [pair["steps"]["rb_net"]["in"]["target_reference_index_source|in_tar_ref_index"],
           pair["steps"]["chainnet"]["in"]["target_reference_index_source|in_tar_ref_index"]],
          ["query_sizes", "target_sizes"])

    check("the wrapper's format default is the chain path's format",
          pair["inputs"]["output_format"]["default"], "axt")
    check("  and it drives the child rather than letting it default",
          pair["steps"]["growler"]["in"]["output_format"], "output_format")
    check("WF-C's gap model is carried over, not defaulted",
          pair["steps"]["axtchain"]["state"]["linear_gap_options"]["linear_gap"], "loose")

    # ⛔ THE STITCH STEPS MUST NAME THE UDT, NOT THE CLASSIC ID. `chainStitchId` is what WF-C's
    # classic edition says and it looks more correct, which is exactly why this is pinned: that id
    # resolves on neither usegalaxy.org nor vgp, because the shed wrapper was never published.
    # Both steps, because only one of them is the exported deliverable and a half-fixed pair would
    # still lint, still import, and fail at the second job.
    check("both stitch steps name the UDT that actually resolves",
          [pair["steps"]["chainstitchid_clean"]["tool_id"], pair["steps"]["rb_stitch"]["tool_id"]],
          ["brc-chain-stitch-id", "brc-chain-stitch-id"])
    check("the wrapper renders", yaml.safe_load(render_pair(child))["label"],
          "Growler pair (one genome pair, through chains)")

    # ------------------------------------------------------------------- the import size guard
    # ⛔ AND IT MUST BE ABLE TO FIRE. A guard that has never rejected anything is a guard nobody
    # has tested. Incompressible text is used because the threshold is on COMPRESSED size: 3,000
    # characters of base64 crossed it on usegalaxy.org while 4,200 characters of "a" did not.
    import base64
    import os

    incompressible = base64.b64encode(os.urandom(3000)).decode()
    check("a real document passes the guard", annotation_complaints(build_pair(child), "x"), [])
    fat = {"doc": incompressible, "steps": {}, "inputs": {}}
    check("an over-long workflow doc IS rejected", len(annotation_complaints(fat, "x")), 1)
    fat_step = {"doc": "", "steps": {"s": {"doc": incompressible}}, "inputs": {}}
    check("  and so is an over-long STEP doc, which is capped separately",
          len(annotation_complaints(fat_step, "x")), 1)
    # ⚠ LENGTH IS THE WRONG MEASURE, and a guard written on characters would pass this and fail
    # the one above -- 4,200 compressible characters import fine.
    check("  while 4,200 compressible characters do NOT trip it",
          annotation_complaints({"doc": "a" * 4200, "steps": {}, "inputs": {}}, "x"), [])
    check("sizes are reported largest first",
          annotation_sizes({"doc": "aaa", "steps": {"s": {"doc": incompressible}}, "inputs": {}})[0][1],
          "step s")

    if failures:
        print(f"\n{len(failures)} test(s) failed")
        return 1
    print("\nall tests passed")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    growler = yaml.safe_load(GROWLER.read_text())
    documents = [(PAIR, render_pair(growler)), (PANEL, render(growler))]
    # ⛔ CHECKED ON EVERY RUN, INCLUDING A PLAIN WRITE. An over-long annotation does not fail here,
    # it fails at `POST /api/workflows` with a 500 and no traceback -- long after this script, and
    # after planemo and gxformat2 have both passed it.
    complaints = [c for path, rendered in documents
                  for c in annotation_complaints(yaml.safe_load(rendered), path.name)]
    if complaints:
        for complaint in complaints:
            print(f"⛔ {complaint}", file=sys.stderr)
        print("Shorten the annotation, or move the long explanation into the tool's own help, "
              "which has no such cap.", file=sys.stderr)
        return 1

    if args.check:
        stale = 0
        for path, rendered in documents:
            if not path.exists():
                print(f"{path.name} is missing; run ./assemble.py", file=sys.stderr)
                stale += 1
            elif path.read_text() != rendered:
                print(f"{path.name} is stale; run ./assemble.py", file=sys.stderr)
                stale += 1
            else:
                print(f"{path.name} is current")
        return 1 if stale else 0

    for path, rendered in documents:
        path.write_text(rendered)
        biggest = annotation_sizes(yaml.safe_load(rendered))[0]
        print(f"wrote {path.name} ({len(rendered.splitlines())} lines; "
              f"largest annotation {biggest[0]:,} zlib bytes, {biggest[1]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
